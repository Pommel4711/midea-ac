def crc8(packet: list[int]) -> int:
    value = 0
    for byte in packet[10:-2]:
        value = CRC8_TABLE[value ^ byte]
    return value


def checksum(packet: list[int]) -> int:
    return (-sum(packet[1:-1])) & 0xFF


def decode_c0_temperature(encoded: int, decimal_nibble: int, celsius: bool = True) -> float:
    """Mirror the documented Midea C0 temperature and decimal correction."""
    result = (encoded - 50) / 2.0
    if not celsius or decimal_nibble == 0:
        return result
    sign = -1.0 if result < 0 else 1.0
    result += sign * (decimal_nibble / 10.0)
    if decimal_nibble >= 5:
        result += sign * 0.5
    return result


class KB35ProtocolVectorsTest(unittest.TestCase):
    def test_golden_get_status_frame_has_version_02_and_valid_checksums(self):
        packet = frame("AA 21 AC 00 00 00 00 00 02 03 41 81 00 FF 03 FF 00 02 00 00 00 00 00 00 00 00 00 00 00 00 03 04 56 0C")
        self.assertEqual(len(packet), packet[1] + 1)
        self.assertEqual(packet[8], 0x02)
        self.assertEqual(packet[-2], crc8(packet))
        self.assertEqual(packet[-1], checksum(packet))

    def test_supplied_status_frame_decodes_but_has_a_checksum_discrepancy(self):
        packet = frame("AA 28 AC 00 00 00 00 00 02 03 C0 01 66 65 7F 7F 00 00 00 00 00 63 69 0A 00 66 00 00 00 00 00 00 00 04 00 00 00 00 28 D4 62")
        self.assertEqual(len(packet), packet[1] + 1)
        self.assertEqual(packet[-2], crc8(packet))
        # The pasted C0 sample ends in 0x62. The documented Midea checksum
        # rule produces 0x61, so it must not be accepted by the controller as
        # a valid golden frame until an untouched UART capture is supplied.
        self.assertEqual(checksum(packet), 0x61)
        self.assertNotEqual(packet[-1], checksum(packet))
        payload = packet[10:]
        self.assertEqual(payload[0], 0xC0)
        self.assertTrue(payload[1] & 0x01)
        self.assertEqual((payload[2] & 0xE0) >> 5, 3)  # DRY
        self.assertEqual((payload[2] & 0x0F) + 16, 22)
        self.assertEqual(payload[3] & 0x7F, 101)  # fixed/special

    def test_temperature_and_mode_encoding(self):
        for temperature, encoded in ((18, 0x62), (19, 0x63), (20, 0x64), (21, 0x65), (22, 0x66), (23, 0x67)):
            self.assertEqual((3 << 5) | (temperature - 16), encoded)
        self.assertEqual((4 << 5) | (25 - 16), 0x89)  # HEAT 25
        self.assertEqual((5 << 5) | (23 - 16), 0xA7)  # FAN_ONLY 23

    def test_fan_swing_frost_turbo_and_gear_values(self):
        self.assertEqual([0, 1, 39, 50, 75, 97, 100, 102], [0x00, 0x01, 0x27, 0x32, 0x4B, 0x61, 0x64, 0x66])
        self.assertEqual({0x30: "off", 0x3C: "vertical", 0x33: "horizontal", 0x3F: "both"}[0x3F], "both")
        self.assertTrue(0x80 & 0x80)  # frost: C0 data[21]
        self.assertTrue((0x20 & 0x20) or (0x00 & 0x02))  # turbo: data[8] OR data[10]
        self.assertEqual({"Normal": 0x64, "75 %": 0x4B, "50 %": 0x32}["50 %"], 0x32)

    def test_c0_temperature_uses_fractional_nibbles_in_celsius_mode(self):
        # Base 24.5 °C plus the documented C0 decimal correction.
        self.assertAlmostEqual(decode_c0_temperature(99, 4), 24.9)
        self.assertAlmostEqual(decode_c0_temperature(99, 6), 25.6)
        # No C0 decimal correction is applied while the status is Fahrenheit.
        self.assertAlmostEqual(decode_c0_temperature(99, 4, celsius=False), 24.5)


